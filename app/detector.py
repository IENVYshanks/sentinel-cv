from __future__ import annotations

import threading
from typing import Any

import cv2

from app.models import Detection


class PersonDetector:
    """Lazy-loaded YOLO detector shared safely by camera workers."""

    def __init__(self, model_name: str, confidence: float = 0.4):
        self.model_name = model_name
        self.confidence = confidence
        self._model: Any = None
        self._lock = threading.Lock()

    def _load(self) -> None:
        if self._model is None:
            from ultralytics import YOLO

            self._model = YOLO(self.model_name)

    def detect(self, frame: Any) -> list[Detection]:
        if self.model_name == "demo":
            return self._detect_demo_people(frame)
        with self._lock:
            self._load()
            results = self._model.predict(
                source=frame,
                classes=[0],
                conf=self.confidence,
                verbose=False,
            )
        detections: list[Detection] = []
        if not results:
            return detections
        for box in results[0].boxes:
            coordinates = box.xyxy[0].tolist()
            confidence = float(box.conf[0])
            detections.append(
                Detection(
                    x1=int(coordinates[0]),
                    y1=int(coordinates[1]),
                    x2=int(coordinates[2]),
                    y2=int(coordinates[3]),
                    confidence=confidence,
                )
            )
        return detections

    @staticmethod
    def _detect_demo_people(frame: Any) -> list[Detection]:
        """Detect the bright-green silhouettes generated by the demo source."""
        mask = cv2.inRange(frame, (0, 200, 0), (100, 255, 100))
        contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        detections: list[Detection] = []
        for contour in contours:
            if cv2.contourArea(contour) < 500:
                continue
            x, y, width, height = cv2.boundingRect(contour)
            detections.append(
                Detection(
                    x1=int(x),
                    y1=int(y),
                    x2=int(x + width),
                    y2=int(y + height),
                    confidence=0.99,
                )
            )
        return sorted(detections, key=lambda detection: (detection.x1, detection.y1))


